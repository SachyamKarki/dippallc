import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const PUBLIC_DIR = path.join(process.cwd(), "public");
const OUT_FILE = path.join(process.cwd(), "src/lib/imagePlaceholders.ts");

const IMAGE_EXT = /\.(jpe?g|png|webp|avif)$/i;

async function collectImages(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectImages(fullPath)));
      continue;
    }
    if (IMAGE_EXT.test(entry.name)) files.push(fullPath);
  }

  return files;
}

async function toBlurDataURL(filePath) {
  const buffer = await sharp(filePath)
    .rotate()
    .resize(20, 20, { fit: "inside", withoutEnlargement: true })
    .blur(1.2)
    .webp({ quality: 18 })
    .toBuffer();

  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

async function main() {
  const files = await collectImages(PUBLIC_DIR);
  const placeholders = {};

  for (const filePath of files.sort()) {
    const publicPath = `/${path.relative(PUBLIC_DIR, filePath).split(path.sep).join("/")}`;
    placeholders[publicPath] = await toBlurDataURL(filePath);
    console.log(`placeholder: ${publicPath}`);
  }

  const body = `// Generated by scripts/generate-image-placeholders.mjs — do not edit by hand.
export const imagePlaceholders = ${JSON.stringify(placeholders, null, 2)} as const;

export function getImagePlaceholder(src: string): string | undefined {
  if (!src || src.startsWith("http://") || src.startsWith("https://") || src.startsWith("data:")) {
    return undefined;
  }

  const normalized = src.startsWith("/") ? src : \`/\${src}\`;
  return imagePlaceholders[normalized as keyof typeof imagePlaceholders];
}
`;

  await fs.writeFile(OUT_FILE, body, "utf8");
  console.log(`\nWrote ${Object.keys(placeholders).length} placeholders → ${OUT_FILE}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
